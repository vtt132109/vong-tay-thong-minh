"""Train the deployed models and write firmware headers.

  include/tiny_fall_model.h     float MLP (42 features)       -> src/ai_model.cpp
  include/cnn_fall_model.h      int8 1D-CNN                   -> src/ai_cnn.cpp
  include/selftest_vectors.h    fixture windows + expected probabilities for the on-device self-test
  dataset/ai_results/final.json training/threshold provenance

Deployed models are trained on subjects 1-18 (early stopping on 19-21) with the firmware-chain +
augmentation windows. The performance claims in the report come from LOSO (run_loso.py), not from these.
Usage: export_final.py [--seed 0] [--thr FLOAT --dbn K/N] (thresholds default to dataset/ai_results/fusion.json)
"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from ai_lab import lab, quant
from ai_lab.data import load_recordings

ROOT = Path(__file__).resolve().parents[2]
INC = ROOT / "include"
RES = ROOT / "dataset" / "ai_results"


def fnum(x) -> str:
    return f"{float(np.float32(x)):.9g}f"


def arr(name, ctype, values, per_line=8, const="static const"):
    v = np.asarray(values).reshape(-1)
    items = [fnum(x) if ctype == "float" else str(int(x)) for x in v]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return f"{const} {ctype} {name}[{len(v)}] = {{\n    " + ",\n    ".join(lines) + ",\n};\n"


def write_mlp_header(fm, thr_single, meta):
    m = fm.model
    W1 = m.l1.weight.detach().numpy()          # (16,42)
    b1 = m.l1.bias.detach().numpy()
    W2 = m.l2.weight.detach().numpy().reshape(-1)
    b2 = float(m.l2.bias.detach().numpy()[0])
    mu, sd = fm.norm
    txt = f"""#pragma once

// tiny_fall_model.h -- float MLP fall classifier (42 features -> 16 tanh -> 1 sigmoid).
// Auto-generated by tools/ai_lab/export_final.py. Do not hand-edit.
//
// Training data : HIFD (real wrist IMU, 21 subjects, 50 Hz) passed through the firmware signal
//                 chain (raw accel with gravity -> 21 Hz low-pass -> +-16 g clip -> first-order
//                 gravity removal alpha 0.98) with random sensor rotation and gyro-bias
//                 augmentation. See BAO_CAO.md section 6 and tools/ai_lab/.
// Features      : exactly the 42 values of tools/hifd_features.md (src/ai_model.cpp).
// Standardise   : z = (x - MEAN) / SCALE.
// Provenance    : {meta}
//
// RESEARCH DEMO ONLY -- NOT A MEDICAL DEVICE.

#define TINY_AI_FEATURE_COUNT 42
#define TINY_AI_HIDDEN 16
#define TINY_AI_THRESHOLD {fnum(thr_single)}

{arr("TINY_AI_MEAN", "float", mu)}
{arr("TINY_AI_SCALE", "float", sd)}
{arr("TINY_AI_W1", "float", W1.reshape(16, 42), 6).replace("TINY_AI_W1[672]", "TINY_AI_W1[16][42]")}
{arr("TINY_AI_B1", "float", b1)}
{arr("TINY_AI_W2", "float", W2)}
static const float TINY_AI_B2 = {fnum(b2)};
"""
    # nested-brace initialiser for the 2-D array
    txt = txt.replace("TINY_AI_W1[16][42] = {\n", "TINY_AI_W1[16][42] = {\n    ", 1)
    (INC / "tiny_fall_model.h").write_text(_fix_w1(txt, W1), encoding="utf-8")


def _fix_w1(txt, W1):
    start = txt.index("static const float TINY_AI_W1")
    end = txt.index("};\n", start) + 3
    rows = ",\n".join("    {" + ", ".join(fnum(x) for x in r) + "}" for r in W1)
    return txt[:start] + "static const float TINY_AI_W1[16][42] = {\n" + rows + ",\n};\n" + txt[end:]


def write_cnn_header(q, thr_fused, thr_cnn, meta):
    L = q["layers"]
    c1, c2, c3 = (l["W"].shape[0] for l in L)
    s_in = q["s_in"]
    inv = 1.0 / (q["sd"] * s_in)
    txt = f"""#pragma once

// cnn_fall_model.h -- int8 1D-CNN fall classifier. Auto-generated by tools/ai_lab/export_final.py.
// Do not hand-edit. Kernel: src/ai_cnn.cpp (bit-exact mirror of tools/ai_lab/quant.py).
// Provenance: {meta}
// RESEARCH DEMO ONLY -- NOT A MEDICAL DEVICE.

#define CNN_IN_CH 7
#define CNN_T 100
#define CNN_C1 {c1}
#define CNN_C2 {c2}
#define CNN_C3 {c3}
#define CNN_T1 50
#define CNN_T2 25
#define CNN_T3 25
#define CNN_THRESHOLD {fnum(thr_cnn)}
#define AI_ENSEMBLE_THRESHOLD {fnum(thr_fused)}

{arr("CNN_IN_MEAN", "float", q["mu"])}
{arr("CNN_IN_INV", "float", inv)}
{arr("CNN_W1", "int8_t", L[0]["W"], 16)}
{arr("CNN_B1", "int32_t", L[0]["b"])}
{arr("CNN_M1", "float", L[0]["M"])}
{arr("CNN_W2", "int8_t", L[1]["W"], 16)}
{arr("CNN_B2", "int32_t", L[1]["b"])}
{arr("CNN_M2", "float", L[1]["M"])}
{arr("CNN_W3", "int8_t", L[2]["W"], 16)}
{arr("CNN_B3", "int32_t", L[2]["b"])}
{arr("CNN_M3", "float", L[2]["M"])}
static const float CNN_S_LAST = {fnum(q["s_last"])};
{arr("CNN_FCW", "float", q["fcw"])}
static const float CNN_FCB = {fnum(q["fcb"])};
"""
    (INC / "cnn_fall_model.h").write_text(txt, encoding="utf-8")


def write_selftest(Wte, p_mlp, p_cnn, picks, labels):
    n = len(picks)
    body = "#pragma once\n\n// Auto-generated by tools/ai_lab/export_final.py: fixture windows (HIFD test subjects passed\n// through the firmware chain) and the probabilities the numpy reference gives. The board\n// re-computes them at boot and prints [SELFTEST] PASS/FAIL.\n\n"
    body += f"#define SELFTEST_N {n}\n"
    body += "static const char *const SELFTEST_NAME[SELFTEST_N] = {" + ", ".join(f'"{l}"' for l in labels) + "};\n"
    body += arr("SELFTEST_P_MLP", "float", p_mlp[picks])
    body += arr("SELFTEST_P_CNN", "float", p_cnn[picks])
    body += f"static const float SELFTEST_WIN[SELFTEST_N][600] = {{\n"
    for i in picks:
        body += "    {" + ", ".join(f"{x:.4f}f" for x in Wte.X[i].reshape(-1)) + "},\n"
    body += "};\n"
    (INC / "selftest_vectors.h").write_text(body, encoding="utf-8")


def main():
    seed = 0
    if "--seed" in sys.argv:
        seed = int(sys.argv[sys.argv.index("--seed") + 1])
    cfg = json.loads((RES / "fusion.json").read_text()) if (RES / "fusion.json").is_file() else {}
    thr_fused = float(cfg.get("thr_fused", 0.90))
    thr_mlp = float(cfg.get("thr_mlp", 0.90))
    thr_cnn = float(cfg.get("thr_cnn", 0.90))
    cnn_cfg = tuple(cfg.get("cnn_cfg", (8, 16, 16)))
    cnn_views = cfg.get("cnn_views", ["fw", "fw_aug0", "fw_aug1", "fw_aug2"])

    recs = load_recordings()
    V = lab.get_views(recs)
    W = V["fw"]
    trm, vam, tem = W.subj <= 18, W.subj >= 19, W.subj >= 19
    aug = ["fw", "fw_aug0", "fw_aug1", "fw_aug2"]
    Wtr = lab._concat([V[v].sub(trm) for v in aug])
    Wva = W.sub(vam)
    print("training MLP-42 ...")
    mlp = lab.fit_mlp(Wtr, Wva, seed)
    print("training CNN ...")
    Wtr_c = lab._concat([V[v].sub(trm) for v in cnn_views])
    cnn = lab.fit_cnn(Wtr_c, Wva, seed, cfg=cnn_cfg)
    q = quant.quantize(cnn, Wtr_c.X[::5])
    Wte = W.sub(tem)
    p_mlp = mlp.predict(Wte)
    p_cnn_f = cnn.predict(Wte)
    p_cnn = quant.int8_forward(q, Wte.X)
    print(f"cnn float vs int8: mean|dp|={np.abs(p_cnn_f - p_cnn).mean():.4f}  MACs={quant.macs(q)}  "
          f"params={sum(p.numel() for p in cnn.model.parameters())}")

    meta = f"seed {seed}, train subjects 1-18, early-stop 19-21, thresholds from LOSO (fusion.json)"
    write_mlp_header(mlp, thr_mlp, meta)
    write_cnn_header(q, thr_fused, thr_cnn, meta)

    # fixtures: strongest fall, mid fall, weak fall, hardest ADL, rest, plain ADL
    y = Wte.y == 1
    keep = Wte.keep
    ens = (p_mlp + p_cnn) / 2
    pos = np.where(y & keep)[0]
    neg = np.where(~y & keep)[0]
    pos_sorted = pos[np.argsort(ens[pos])]
    picks = [pos_sorted[-1], pos_sorted[len(pos_sorted) // 2], pos_sorted[len(pos_sorted) // 6],
             neg[np.argmax(ens[neg])], neg[np.argmin(ens[neg])], neg[len(neg) // 2]]
    labels = ["fall_strong", "fall_mid", "fall_weak", "adl_hardest", "adl_rest", "adl_plain"]
    write_selftest(Wte, p_mlp, p_cnn, np.array(picks), labels)
    for lab_, i in zip(labels, picks):
        print(f"  fixture {lab_:12s} mlp {p_mlp[i]:.4f} cnn {p_cnn[i]:.4f} (scen {Wte.scen[i]})")
    (RES / "final.json").write_text(json.dumps({"seed": seed, "meta": meta, "thr_fused": thr_fused,
                                                "thr_mlp": thr_mlp, "thr_cnn": thr_cnn, "cnn_cfg": cnn_cfg,
                                                "cnn_views": cnn_views, "macs": quant.macs(q)}, indent=1))
    import pickle
    pickle.dump({"mlp": mlp, "cnn": cnn, "q": q}, open(RES / "final_models.pkl", "wb"))
    print("headers written")


if __name__ == "__main__":
    main()
