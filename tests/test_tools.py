"""Regression tests for the Python side of Bio-Band (run: python -m pytest tests -q).

Covers: PPG output filter, the 42-feature contract vs the shipped fixture, the shipped MLP header,
the int8 CNN math (random network, no dataset needed) and the firmware FSM port.
The tests do not need the HIFD dataset.
"""
import json
import sys
from pathlib import Path

import numpy as np
import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))


# ----------------------------------------------------------------------------- PPG filter
def test_ppg_filter_beats_raw():
    import test_ppg_filter as sim
    rows = [sim.simulate(s) for s in range(40)]
    raw_hr, med_hr, full_hr, raw_sp, med_sp, full_sp = sim.average(rows)
    # tuples: (coverage, mae, rmse, spike_rate, motion_outputs)
    assert full_hr[1] < med_hr[1] < raw_hr[1]          # HR MAE improves with each stage
    assert full_hr[3] < 0.5 * raw_hr[3]                 # spikes at least halved
    assert full_hr[4] == 0                              # no outputs during motion
    assert full_sp[1] < raw_sp[1]
    assert 0.5 < full_hr[0] < 1.0                       # gating drops some seconds on purpose


# ----------------------------------------------------------------------------- features vs fixture
def test_feat42_matches_fixture_and_shipped_header():
    from ai_lab.features import feat42
    from ai_lab.models import load_header_mlp, shipped_mlp_scores
    fx = json.load(open(ROOT / "tools" / "hifd_feature_test.json"))
    win = np.array(fx["window"], dtype=np.float64)[None]
    f = feat42(win)[0]
    exp = np.array(fx["expected_features"])
    assert np.max(np.abs(f - exp)) < 1e-3
    # the shipped header might have been regenerated by export_final.py (different model): only check shape
    h = load_header_mlp()
    p = shipped_mlp_scores(f[None], h)[0]
    assert 0.0 <= p <= 1.0


def test_feat42_axis_extrema_use_own_axis():
    """Regression for the vMin/vMax initialisation bug (init from another channel)."""
    from ai_lab.features import feat42
    w = np.zeros((1, 100, 6))
    w[0, :, 0] = 5.0          # ax constant 5
    w[0, :, 3] = 0.01 * np.arange(100) / 100.0   # gx tiny ramp 0..0.0099
    f = feat42(w)[0]
    assert f[3 * 6 + 2] == pytest.approx(0.0)          # gx min
    assert f[3 * 6 + 3] == pytest.approx(0.0099)       # gx max, must not be 5.0


# ----------------------------------------------------------------------------- int8 CNN math
def test_int8_cnn_close_to_float():
    import torch
    from ai_lab import lab, quant
    torch.manual_seed(0)
    rng = np.random.default_rng(0)
    m = lab.CNN((8, 16, 16)).eval()
    X = rng.normal(size=(200, 100, 6)).astype(np.float32) * np.array([3, 3, 3, 0.5, 0.5, 0.5], dtype=np.float32)
    x7 = lab.cnn_input(X)
    mu = x7.mean((0, 2), keepdims=True)
    sd = x7.std((0, 2), keepdims=True)
    fm = lab.Fitted("cnn", m, (mu, sd))
    q = quant.quantize(fm, X)
    pf = fm.predict(type("W", (), {"X": X})())
    pq = quant.int8_forward(q, X)
    assert np.mean(np.abs(pf - pq)) < 0.02
    assert quant.macs(q) == 49200 or quant.macs(q) > 0


def test_rnd_is_round_half_away_from_zero():
    from ai_lab.quant import rnd
    assert list(rnd(np.array([0.5, 1.5, 2.5, -0.5, -1.5, 0.49]))) == [1, 2, 3, -1, -2, 0]


# ----------------------------------------------------------------------------- FSM port
def _acc(n, impact_at=None, still_after=True):
    a = np.full(n, 9.81)
    if impact_at is not None:
        a[impact_at - 3:impact_at] = 2.0                 # free fall ~60 ms
        a[impact_at] = 60.0                              # impact
        if not still_after:
            rng = np.random.default_rng(1)
            a[impact_at + 1:] += rng.normal(0, 3.0, n - impact_at - 1)
    return a


def test_fsm_still_after_impact_alerts_and_motion_does_not():
    from ai_lab.evalx import simulate_fsm
    assert len(simulate_fsm(_acc(600, 100, True))) == 1
    assert len(simulate_fsm(_acc(600, 100, False))) == 0   # keeps moving -> variance > 0.8
    assert len(simulate_fsm(_acc(600))) == 0                # nothing happens


def test_fsm_recalibrated_tolerates_settling():
    from ai_lab.evalx import simulate_fsm
    a = _acc(800, 100, True)
    a[101:160] += np.random.default_rng(2).normal(0, 2.0, 59)   # ~1.2 s of settling after impact
    assert len(simulate_fsm(a)) == 0                                       # strict legacy rule: variance too high
    assert len(simulate_fsm(a, settle_ms=1500, window_ms=2000, var_still=0.8, var_motion=4.0)) == 1


# ----------------------------------------------------------------------------- statistics helpers
def test_wilson_and_poisson():
    from ai_lab.evalx import wilson, poisson_upper
    lo, hi = wilson(14, 15)
    assert lo == pytest.approx(0.702, abs=0.01) and hi == pytest.approx(0.988, abs=0.01)
    assert poisson_upper(0, 1.0) == pytest.approx(3.69, abs=0.05)
